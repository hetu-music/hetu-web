-- 第四段：老表补齐第八节的约定（见 docs/DATABASE.md 第八节、第九节「第四段」）
--
-- 1. 主键：user_requests、audit_logs 由 uuid 改 bigint identity（按创建时间编号）；
--    emotions.id 由 smallint 改 bigint identity，song_emotions.emotion_id 跟着改。
-- 2. 时间戳：每张表的创建时间都叫 created_at。users、emotions 补上；audit_logs.changed_at、
--    stream_grants.issued_at、song_collation_revisers.first_at 改名。
--    user_requests.updated_at 没人读（回复时间看 replied_at），删掉；没人用的 updated_at() 函数一并删。
-- 3. 外键：audit_logs.user_id 加外键指 users（on delete set null，与各表的 created_by 一样）。
--    quiz_results.song_ids 是快照，不加外键，类型改 bigint[] 与 songs.id 一致。
--
-- 引用改名列的函数（ensure_draft、claim_stream_grant）与定时任务一并重建；
-- 依赖 song_emotions.emotion_id 的视图 published_song_emotions 先删后建。

-- ════════════════════════════════════════════════════════════════════════════
-- 前提检查
-- ════════════════════════════════════════════════════════════════════════════

do $$
declare
  n bigint;
begin
  select count(*) into n from public.audit_logs a
  where a.user_id is not null
    and not exists (select 1 from public.users u where u.id = a.user_id);
  if n > 0 then
    raise exception '有 % 条审计日志的 user_id 在 users 里找不到', n;
  end if;

  select count(*) into n from public.users u
  where not exists (select 1 from auth.users a where a.id = u.id);
  if n > 0 then
    raise exception '有 % 个用户在 auth.users 里找不到', n;
  end if;
end;
$$;

create temp table phase4_counts on commit drop as
select
  (select count(*) from public.audit_logs) as audit_logs,
  (select count(*) from public.user_requests) as user_requests,
  (select count(*) from public.emotions) as emotions,
  (select count(*) from public.song_emotions) as song_emotions,
  (select count(*) from public.users) as users;

