-- ════════════════════════════════════════════════════════════════════════════
-- navid_song 记下曲目的格式与时长，播放时直接读，不再每次现场问 Navidrome。
--
--   suffix    文件扩展名（mp3、flac…）：mp3 直接发原文件，其余转码
--   duration  音频文件的实际时长（秒）：opus 转码流没有长度，进度条靠它；
--             也用来算播放链接的过期时间。和 music.length（资料里录的时长）不是一回事
--
-- 由 Navidrome 同步写入：新建、替换映射时一并写；每次同步还会把现有映射里
-- 与曲库不一致的刷新一遍，所以执行这个文件后跑一次同步即可回填。
-- 尚未回填（任一项为 null）时 stream-url 会退回现场查询，先执行这个文件不影响播放。
--
-- 只加列：表级授权自动覆盖新列，不用另外 grant。
-- ════════════════════════════════════════════════════════════════════════════

alter table public.navid_song
  add column suffix text,
  add column duration integer;
