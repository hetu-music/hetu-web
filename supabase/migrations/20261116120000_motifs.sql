-- ════════════════════════════════════════════════════════════════════════════
-- 视图：part_motif_ids 是读时展开的「同时算进」
-- 标注挂在词的默认母题上时，这个词登记的 part 母题都算进；挂在多义候选上时不算
-- ════════════════════════════════════════════════════════════════════════════

create view public.published_song_imagery with (security_invoker = true) as
select
  s.id as song_id,
  i.version_id,
  i.id,
  i.imagery_id,
  i.motif_id,
  coalesce(parts.ids, '{}'::bigint[]) as part_motif_ids,
  i.created_at
from public.songs s
join public.song_imagery i on i.version_id = s.live_version_id
left join lateral (
  select array_agg(p.motif_id order by p.motif_id) as ids
  from public.imagery_motifs p
  join public.imagery_motifs m
    on m.imagery_id = p.imagery_id and m.role = 'primary' and m.motif_id = i.motif_id
  where p.imagery_id = i.imagery_id and p.role = 'part'
) parts on true;

comment on view public.published_song_imagery is
  '线上版本的意象标注，一条标注一行。part_motif_ids 是读时展开的「同时算进」；时间标签由服务端按歌词算';

create view public.working_song_imagery with (security_invoker = true) as
select
  w.id as song_id,
  w.title as song_title,
  w.album as song_album,
  i.version_id,
  i.id,
  i.imagery_id,
  im.name as imagery_name,
  i.motif_id,
  mo.name as motif_name,
  coalesce(parts.ids, '{}'::bigint[]) as part_motif_ids,
  i.created_at
from public.working_songs w
join public.song_imagery i on i.version_id = w.version_id
join public.imagery im on im.id = i.imagery_id
join public.motifs mo on mo.id = i.motif_id
left join lateral (
  select array_agg(p.motif_id order by p.motif_id) as ids
  from public.imagery_motifs p
  join public.imagery_motifs m
    on m.imagery_id = p.imagery_id and m.role = 'primary' and m.motif_id = i.motif_id
  where p.imagery_id = i.imagery_id and p.role = 'part'
) parts on true;

comment on view public.working_song_imagery is
  '工作版本的意象标注，带歌名、词名、母题名，一条标注一行。part_motif_ids 同 published_song_imagery';

-- 后台词典：全部词及标注条数（按工作版本，含争议歌曲）
create view public.imagery_summary_all with (security_invoker = true) as
select
  im.id,
  im.name,
  count(i.id)::integer as count
from public.imagery im
left join public.working_song_imagery i on i.imagery_id = im.id
group by im.id, im.name;

