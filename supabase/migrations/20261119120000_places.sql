-- 河图志：地点与歌的对应（见 docs/PLACES.md 第二节）
--
-- 1. places：地点，独立的词表，不分版本（与 imagery 相当）。
-- 2. song_places：哪首歌写到哪处、在哪处演出过，挂在版本上，随发布（与 song_imagery 相当）。
--    歌里的地方（setting）可以按行号 + 时间 + 引文挂在一句歌词上，与校记、评论同一套；
--    挑不出哪一句的挂在整首歌上。演出场馆（venue）不引歌词。
-- 3. ensure_draft 开草稿时一并复制 song_places；公开端读 published_song_places。
--
-- 读者的「到过」（place_visits）在做打卡时另建。
-- 后台还没有读写这两张表的界面，authenticated 暂不授权，做后台时再按代码实际用到的补。

-- ════════════════════════════════════════════════════════════════════════════
-- 1. places
-- ════════════════════════════════════════════════════════════════════════════

create table public.places (
  id bigint generated by default as identity primary key,
  name text not null check (name = btrim(name) and name <> ''),
  full_name text check (full_name = btrim(full_name) and full_name <> ''),
  region text not null check (region = btrim(region) and region <> ''),
  lat numeric(9, 6) check (lat between -90 and 90),
  lng numeric(9, 6) check (lng between -180 and 180),
  created_at timestamptz not null default now(),
  unique (name, region),
  check ((lat is null) = (lng is null)),
  check (full_name is distinct from name)
);

comment on table public.places is
  '河图志的地点。不分版本，后台直接改。水系图上的示意位置是手排的，放在代码里按 id 对应';
comment on column public.places.name is '图上的短名：「午门」';
comment on column public.places.full_name is '全称，与短名相同时留空：「故宫博物院·午门」';
comment on column public.places.region is '「北京」「湖南 · 长沙」，以「 · 」分级';
comment on column public.places.lat is 'WGS84 纬度，给「我在附近」用；与 lng 同时为空或同时有值';

alter table public.places enable row level security;

create trigger places_audit
  after insert or update or delete on public.places
  for each row execute function public.record_audit_log();

grant all on public.places to service_role;

-- ════════════════════════════════════════════════════════════════════════════
-- 2. song_places
-- ════════════════════════════════════════════════════════════════════════════

create table public.song_places (
  version_id bigint not null references public.song_versions (id) on delete cascade,
  id bigint generated by default as identity,
  place_id bigint not null references public.places (id) on delete restrict,
  relation text not null check (relation in ('setting', 'venue')),
  anchor_index integer check (anchor_index >= 0),
  anchor_time numeric(8, 3),
  anchor_quote text check (char_length(anchor_quote) between 1 and 200),
  note text check (note = btrim(note) and char_length(note) between 1 and 500),
  created_at timestamptz not null default now(),
  created_by uuid default auth.uid() references public.users (id) on delete set null,
  primary key (version_id, id),
  -- 挂句时行号与引文都要有，时间可空（纯文本歌词没有时间）；演出场馆不引歌词
  check ((anchor_index is null) = (anchor_quote is null)),
  check (anchor_time is null or anchor_quote is not null),
  check (relation <> 'venue' or anchor_quote is null),
  unique nulls not distinct (version_id, place_id, relation, anchor_quote)
);

comment on table public.song_places is
  '歌与地点的对应，挂在版本上。歌里的地方（setting）可按行号 + 时间 + 引文挂在一句上，改词后按引文重定位，挑不出句子的挂整首歌；演出场馆（venue）不引歌词。一处地点引了几句就写几行';
comment on column public.song_places.anchor_quote is '那一句歌词的全文（toQuote），与校记、评论的引文同一写法';
comment on column public.song_places.note is '「2016 年心时纪河图现场」';

create index song_places_place_id on public.song_places (place_id);

alter table public.song_places enable row level security;

create trigger song_places_guard
  before insert or update or delete on public.song_places
  for each row execute function public.editorial_guard();

create trigger song_places_audit
  after insert or update or delete on public.song_places
  for each row execute function public.record_audit_log();

grant all on public.song_places to service_role;

create view public.published_song_places with (security_invoker = true) as
select s.id as song_id, p.version_id, p.id, p.place_id, p.relation,
  p.anchor_index, p.anchor_time, p.anchor_quote, p.note
from public.songs s
join public.song_places p on p.version_id = s.live_version_id;

comment on view public.published_song_places is '线上版本的歌与地点对应';

grant select on public.published_song_places to service_role;

-- ════════════════════════════════════════════════════════════════════════════
-- 3. ensure_draft 一并复制 song_places
-- ════════════════════════════════════════════════════════════════════════════

create or replace function public.ensure_draft(p_song_id bigint) returns bigint
  language plpgsql security definer
  set search_path = ''
as $$
declare
  draft bigint;
  src bigint;
begin
  perform public.assert_role(array['bot', 'admin', 'super']);

  -- 锁住这首歌，两个请求同时开草稿时只开一份
  perform 1 from public.songs where id = p_song_id for update;
  if not found then
    raise exception '歌曲不存在' using errcode = 'P0002';
  end if;

  select id into draft
  from public.song_versions
  where song_id = p_song_id and published_at is null;
  if found then
    return draft;
  end if;

  select id into src
  from public.song_versions
  where song_id = p_song_id
  order by published_at desc
  limit 1;
  if src is null then
    raise exception '这首歌没有任何版本' using errcode = 'P0002';
  end if;

  perform set_config('hetu.copying', 'on', true);

  insert into public.song_versions (
    song_id, title, date, album, track, tracktotal, discnumber, disctotal,
    artist, lyricist, composer, arranger, albumartist, genre, type, length,
    lyrics, lyrics_start, comment, dispute_note, hascover, nmn_status,
    created_by, updated_at, updated_by
  )
  select
    song_id, title, date, album, track, tracktotal, discnumber, disctotal,
    artist, lyricist, composer, arranger, albumartist, genre, type, length,
    lyrics, lyrics_start, comment, dispute_note, hascover, nmn_status,
    auth.uid(), updated_at, updated_by     -- 沿用源版本的 updated_at：打开着的表单不会误报冲突
  from public.song_versions
  where id = src
  returning id into draft;

  insert into public.song_imagery (version_id, id, imagery_id, motif_id, created_at, created_by)
  select draft, id, imagery_id, motif_id, created_at, created_by
  from public.song_imagery where version_id = src;

  insert into public.song_emotions (version_id, emotion_id, rank, created_at, created_by)
  select draft, emotion_id, rank, created_at, created_by
  from public.song_emotions where version_id = src;

  insert into public.song_collations (
    version_id, id, anchor, anchor_index, anchor_time, anchor_quote, kind, quote,
    sung, body, date, created_by, updated_by, created_at, updated_at
  )
  select
    draft, id, anchor, anchor_index, anchor_time, anchor_quote, kind, quote,
    sung, body, date, created_by, updated_by, created_at, updated_at
  from public.song_collations where version_id = src;

  insert into public.song_collation_revisers (version_id, collation_id, user_id, created_at)
  select draft, collation_id, user_id, created_at
  from public.song_collation_revisers where version_id = src;

  insert into public.song_places (
    version_id, id, place_id, relation, anchor_index, anchor_time, anchor_quote,
    note, created_at, created_by
  )
  select
    draft, id, place_id, relation, anchor_index, anchor_time, anchor_quote,
    note, created_at, created_by
  from public.song_places where version_id = src;

  perform set_config('hetu.copying', 'off', true);
  return draft;
end;
$$;
