-- 6. 合并重复标注：保留 id 最小的一条，时间标签取并集
with grp as (
  select min(id) as keep_id, song_id, imagery_id, category_id,
         array(select distinct t from public.imagery_occurrences x, unnest(x.lyric_timetag) t
               where x.song_id = o.song_id and x.imagery_id = o.imagery_id and x.category_id = o.category_id
               order by t) as tags
  from public.imagery_occurrences o
  group by song_id, imagery_id, category_id
  having count(*) > 1
)
update public.imagery_occurrences o set lyric_timetag = grp.tags
from grp where o.id = grp.keep_id;

