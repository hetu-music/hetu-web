create table public.motifs (
  id bigint generated by default as identity primary key,
  name text not null unique,
  category_id bigint not null references public.imagery_categories (id),
  description text,
  created_at timestamptz not null default now()
);

comment on table public.motifs is
  '母题：标注与词登记挂的那一层（见 IMAGERY.md）。id 沿用原分类树第三级，/imagery/[id] 的地址不变';
comment on column public.motifs.description is
  '这个母题指什么。后台新建时必填；拆表前建的大多没写';

insert into public.motifs (id, name, category_id, description, created_at)
select id, name, parent_id, nullif(btrim(description), ''), created_at
from public.imagery_categories
where level = 3;

-- 新母题的 id 接在类别、母题之后，不与任何旧分类的 id 重合
select setval(
  pg_get_serial_sequence('public.motifs', 'id'),
  greatest(
    (select max(id) from public.motifs),
    (select max(id) from public.imagery_categories),
    1
  )
);

create index motifs_category_id on public.motifs (category_id);

