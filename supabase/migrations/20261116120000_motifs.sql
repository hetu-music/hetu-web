-- 第二段：母题拆表；时间标签与「同时算进」改为读时计算（见 docs/DATABASE.md 第四、五节、第九节「第二段」）
--
-- 1. 分类树的第三级拆成 motifs（id 沿用，/imagery/[id] 的地址不变）；imagery_categories 只留十七个类别，
--    门类改成一列 domain，去掉 parent_id、level。
-- 2. imagery_motifs、song_imagery 的 category_id 改名 motif_id，外键指 motifs。
-- 3. song_imagery 去掉 lyric_timetag（服务端按同一版本的歌词算），删掉「同时算进」补写的行
--    （视图按 imagery_motifs 算出 part_motif_ids）。删完每个版本里一个词只有一条，加唯一约束。
--
-- 已发布的版本冻结，但补写的行与时间标签都是派生数据，删掉不改变任何版本的内容；
-- 这里临时关掉守卫与审计触发器，迁移末尾打开。

-- ════════════════════════════════════════════════════════════════════════════
-- 前提检查：任何一条不满足就停下，整个迁移回滚
-- ════════════════════════════════════════════════════════════════════════════

do $$
declare
  bad text;
begin
  -- 分类树恰好三层：门类没有上级，类别的上级是门类，母题的上级是类别
  select string_agg(format('%s(%s)', c.id, c.name), ', ') into bad
  from public.imagery_categories c
  left join public.imagery_categories p on p.id = c.parent_id
  where c.level is null
     or c.level not in (1, 2, 3)
     or (c.level = 1 and c.parent_id is not null)
     or (c.level > 1 and p.level is distinct from c.level - 1);
  if bad is not null then
    raise exception '分类树不是规整的三层：%', bad;
  end if;

  select string_agg(name, ', ') into bad
  from public.imagery_categories
  where level = 1 and name not in ('自然', '人文', '情志');
  if bad is not null then
    raise exception '有不认识的门类：%', bad;
  end if;

  -- 标注与词登记只挂在母题上
  select string_agg(distinct c.name, ', ') into bad
  from public.song_imagery i
  join public.imagery_categories c on c.id = i.category_id
  where c.level <> 3;
  if bad is not null then
    raise exception '有标注挂在母题以外的分类上：%', bad;
  end if;

  select string_agg(distinct c.name, ', ') into bad
  from public.imagery_motifs m
  join public.imagery_categories c on c.id = m.category_id
  where c.level <> 3;
  if bad is not null then
    raise exception '有词登记在母题以外的分类上：%', bad;
  end if;
end $$;

-- 迁移前的行数，末尾核对
create temp table phase2_counts on commit drop as
select
  (select count(*) from public.imagery_categories where level = 2) as categories,
  (select count(*) from public.imagery_categories where level = 3) as motifs,
  (select count(*) from public.imagery_motifs) as registrations,
  (select count(*) from public.song_imagery) as annotations;

-- 补写的「同时算进」：挂在词的 part 母题上，且同一版本里这个词另有一条挂在它的默认母题上
create temp table phase2_parts on commit drop as
select i.version_id, i.id, i.imagery_id, i.category_id
from public.song_imagery i
join public.imagery_motifs p
  on p.imagery_id = i.imagery_id and p.category_id = i.category_id and p.role = 'part'
where exists (
  select 1
  from public.song_imagery main
  join public.imagery_motifs m
    on m.imagery_id = main.imagery_id and m.category_id = main.category_id and m.role = 'primary'
  where main.version_id = i.version_id and main.imagery_id = i.imagery_id
);

