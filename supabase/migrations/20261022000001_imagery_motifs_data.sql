-- 校验：每个词都有默认母题，每条标注都挂在它的候选母题上
do $$
declare
  missing text;
  bad int;
begin
  select string_agg(i.name, '、') into missing
  from public.imagery i
  where not exists (select 1 from public.imagery_motifs m where m.imagery_id = i.id and m.role = 'primary');
  if missing is not null then
    raise exception '以下意象词没有母题，先补映射：%', missing;
  end if;

  select count(*) into bad
  from public.imagery_occurrences o
  where not exists (select 1 from public.imagery_motifs m
                    where m.imagery_id = o.imagery_id and m.category_id = o.category_id);
  if bad > 0 then
    raise exception '% 条标注没有挂在候选母题上', bad;
  end if;
end $$;

