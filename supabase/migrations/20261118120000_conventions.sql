-- 断言
-- ════════════════════════════════════════════════════════════════════════════

do $$
declare
  c record;
  bad text;
begin
  select * into c from phase4_counts;
  if (select count(*) from public.audit_logs) <> c.audit_logs
     or (select count(*) from public.user_requests) <> c.user_requests
     or (select count(*) from public.emotions) <> c.emotions
     or (select count(*) from public.song_emotions) <> c.song_emotions
     or (select count(*) from public.users) <> c.users then
    raise exception '行数对不上';
  end if;

  -- 每张表都有非空的 created_at
  select string_agg(t.table_name, ', ') into bad
  from information_schema.tables t
  where t.table_schema = 'public' and t.table_type = 'BASE TABLE'
    and not exists (
      select 1 from information_schema.columns col
      where col.table_schema = 'public' and col.table_name = t.table_name
        and col.column_name = 'created_at' and col.is_nullable = 'NO'
    );
  if bad is not null then
    raise exception '这些表没有非空的 created_at：%', bad;
  end if;

  -- 实体没有 uuid 主键，users 除外（跟 auth.users）；关系表的复合主键里有 user_id 不算
  select string_agg(cl.relname, ', ') into bad
  from pg_constraint con
  join pg_class cl on cl.oid = con.conrelid
  join pg_namespace ns on ns.oid = cl.relnamespace and ns.nspname = 'public'
  join pg_attribute att on att.attrelid = cl.oid and att.attnum = con.conkey[1]
  where con.contype = 'p' and cardinality(con.conkey) = 1
    and att.atttypid = 'uuid'::regtype and cl.relname <> 'users';
  if bad is not null then
    raise exception '这些表还是 uuid 主键：%', bad;
  end if;

  -- anon 仍然没有任何权限（新建的视图、列不能带出权限）
  select string_agg(distinct cl.relname, ', ') into bad
  from pg_class cl
  join pg_namespace ns on ns.oid = cl.relnamespace and ns.nspname = 'public'
  where cl.relkind in ('r', 'v', 'm', 'p')
    and exists (select 1 from aclexplode(cl.relacl) a where a.grantee = 'anon'::regrole);
  if bad is not null then
    raise exception 'anon 有权限：%', bad;
  end if;
end;
$$;
